const expr = (type, value, swift) => {
  const optional = type.endsWith('?');
  type = type.replace('?', '');
  const basic = (v) =>
    ({
      decimal: swift ? `String(${v})` : `${v}.toString()`,
      number: swift ? `NSNumber(value: ${v})` : `${v}.toDouble()`,
      bool: v,
      string: v,
      strings: v,
      enum: `rgbEnum(${v})`,
      record: `rgbDto(${v})`,
      records: swift ? `${v}.map { rgbDto($0) }` : `${v}.map { rgbDto(it) }`,
    })[type];
  if (!optional) return basic(value);
  return swift
    ? `${value}.map { ${basic('$0')} as Any } ?? NSNull()`
    : `${value}?.let { ${basic('it')} }`;
};
