#!/usr/bin/env node
// Thin platform adapters are generated from the public typed spec. All wallet
// calls go through generated UniFFI bindings in the platform session stores.
import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = ts.createSourceFile(
  'NativeRgbLib.ts',
  fs.readFileSync(path.join(root, 'src/binding/NativeRgbLib.ts'), 'utf8'),
  ts.ScriptTarget.Latest,
  true
);
const spec = source.statements.find(
  (s) => ts.isInterfaceDeclaration(s) && s.name.text === 'Spec'
);
const methods = spec.members.map((m) => ({
  name: m.name.getText(source),
  params: m.parameters.map((p) => {
    const types = ts.isUnionTypeNode(p.type) ? p.type.types : [p.type];
    const nullable = types.some((t) => t.getText(source) === 'null');
    const kind = types
      .find((t) => t.getText(source) !== 'null')
      .getText(source);
    if (!['string', 'number', 'boolean', 'string[]'].includes(kind))
      throw new Error(`Unsupported bridge parameter: ${kind}`);
    return { name: p.name.getText(source), kind, nullable };
  }),
}));
const objcType = (p) =>
  p.kind === 'string'
    ? 'NSString *'
    : p.kind === 'string[]'
      ? 'NSArray *'
      : p.nullable
        ? 'NSNumber *'
        : p.kind === 'boolean'
          ? 'BOOL'
          : 'double';
const objcValue = (p) =>
  ['number', 'boolean'].includes(p.kind) && !p.nullable
    ? `@(${p.name})`
    : `${p.name} ?: [NSNull null]`;
const iosMethods = methods
  .map(({ name, params }) => {
    const signature = params.length
      ? params
          .map((p, i) => `${i ? p.name : name}:(${objcType(p)})${p.name}`)
          .join(' ') + ' resolve:(RCTPromiseResolveBlock)resolve'
      : `${name}:(RCTPromiseResolveBlock)resolve`;
    return `- (void)${signature} reject:(RCTPromiseRejectBlock)reject {
  [self invoke:@"${name}" params:@{${params.map((p) => `@"${p.name}": ${objcValue(p)}`).join(', ')}} resolve:resolve reject:reject];
}`;
  })
  .join('\n\n');
const ios = `// Generated by scripts/generate-rgb-lib-bridge.mjs. Do not edit.
// Rgb.podspec defines RGB_LIB_BINDINGS when ios/RgbLibBindings is installed.
#if RGB_LIB_BINDINGS
#import <RgbSpec/RgbSpec.h>
#import <React/RCTInvalidating.h>
#if __has_include(<Rgb/Rgb-Swift.h>)
#import <Rgb/Rgb-Swift.h>
#else
#import "Rgb-Swift.h"
#endif
#import "RgbLibDispatcher.h"

@interface RgbLib : NSObject <NativeRgbLibSpec, RCTInvalidating>
@end
@implementation RgbLib {
  // Per-handle queues, adoption and invalidation live in RgbLibDispatcher.
  RgbLibDispatcher *_dispatcher;
}
RCT_EXPORT_MODULE(RgbLib)
+ (BOOL)requiresMainQueueSetup { return NO; }
- (instancetype)init {
  if ((self = [super init])) {
    _dispatcher = [[RgbLibDispatcher alloc] initWithExecute:^NSDictionary *(NSString *operation, NSDictionary *params) {
      return [RgbLibSwiftHelper execute:operation params:params];
    }];
  }
  return self;
}
- (std::shared_ptr<facebook::react::TurboModule>)getTurboModule:(const facebook::react::ObjCTurboModule::InitParams &)params {
  return std::make_shared<facebook::react::NativeRgbLibSpecJSI>(params);
}
- (void)invoke:(NSString *)operation params:(NSDictionary *)params resolve:(RCTPromiseResolveBlock)resolve reject:(RCTPromiseRejectBlock)reject {
  [_dispatcher invoke:operation params:params resolve:^(id result) { resolve(result); } reject:^(NSString *code, NSString *message) { reject(code, message, nil); }];
}
- (void)invalidate {
  [_dispatcher invalidate];
}
${iosMethods}
@end
#endif
`;
const kotlinType = (p) =>
  ({
    'string': 'String',
    'number': 'Double',
    'boolean': 'Boolean',
    'string[]': 'ReadableArray',
  })[p.kind] + (p.nullable ? '?' : '');
const kotlinMethods = methods
  .map(
    ({ name, params }) =>
      `  override fun ${name}(${[
        ...params.map((p) => `${p.name}: ${kotlinType(p)}`),
        'promise: Promise',
      ].join(
        ', '
      )}) = invoke("${name}", mapOf(${params.map((p) => `"${p.name}" to ${p.kind === 'string[]' ? `${p.name}.toArrayList()` : p.name}`).join(', ')}), promise)`
  )
  .join('\n\n');
const android = `// Generated by scripts/generate-rgb-lib-bridge.mjs. Do not edit.
package com.rgbsdkrn

import com.facebook.react.bridge.*
import com.facebook.react.module.annotations.ReactModule
import com.utexo.RgbLibException

@ReactModule(name = RgbLibModule.NAME)
class RgbLibModule(context: ReactApplicationContext) : NativeRgbLibSpec(context) {
  // The AAR ships its provenance as an asset; getRuntimeInfo reports it.
  private val store = RgbLibSessionStore {
    runCatching { context.assets.open("rgb-lib-bfa-version.json").bufferedReader().use { it.readText() } }.getOrNull()
  }
  // Per-handle queues, adoption and invalidation live in RgbLibDispatcher.
  private val dispatcher = RgbLibDispatcher(store::execute, this::rejection)
  override fun getName() = NAME

  private fun rejection(error: Throwable): Pair<String, String?> = when (error) {
    is RgbLibBridgeError -> error.code to error.message
    is RgbLibException -> rgbLibErrorCode(error) to error.message
    is UnsatisfiedLinkError -> "NATIVE_BACKEND_UNAVAILABLE" to "RGB Lib native library failed to load; rebuild the app"
    // Do not include request data or credentials in a bridge error.
    else -> "NATIVE_BRIDGE_ERROR" to "RGB Lib native bridge operation failed"
  }
  private fun convert(value: Any?): Any? = when(value) {
    null -> null
    is Map<*, *> -> Arguments.makeNativeMap(value.entries.associate { it.key as String to convert(it.value) })
    is List<*> -> Arguments.makeNativeArray(value.map { convert(it) })
    is Number -> value.toDouble()
    else -> value
  }
  private fun invoke(operation: String, params: Map<String, Any?>, promise: Promise) =
    dispatcher.invoke(operation, params, object : RgbLibDispatcher.Reply {
      override fun resolve(value: Any?) = promise.resolve(convert(value))
      override fun reject(code: String, message: String?) = promise.reject(code, message)
    })
  override fun invalidate() {
    dispatcher.invalidate()
    super.invalidate()
  }
${kotlinMethods}
  companion object { const val NAME = "RgbLib" }
}
`;
for (const [file, content] of [
  ['ios/RgbLib.mm', ios],
  ['android/src/main/java/com/rgbsdkrn/RgbLibModule.kt', android],
]) {
  const dest = path.join(root, file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== content)
      throw new Error(`${file} needs regeneration`);
  } else fs.writeFileSync(dest, content);
}
