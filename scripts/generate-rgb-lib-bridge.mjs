#!/usr/bin/env node
// Thin platform adapters are generated from the public typed spec. All wallet
// calls go through generated UniFFI bindings in the platform session stores.
import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = ts.createSourceFile(
  'NativeRgbLib.ts',
  fs.readFileSync(path.join(root, 'src/binding/NativeRgbLib.ts'), 'utf8'),
  ts.ScriptTarget.Latest,
  true
);
const spec = source.statements.find(
  (s) => ts.isInterfaceDeclaration(s) && s.name.text === 'Spec'
);
const methods = spec.members.map((m) => ({
  name: m.name.getText(source),
  params: m.parameters.map((p) => {
    const types = ts.isUnionTypeNode(p.type) ? p.type.types : [p.type];
    const nullable = types.some((t) => t.getText(source) === 'null');
    const kind = types
      .find((t) => t.getText(source) !== 'null')
      .getText(source);
    if (!['string', 'number', 'boolean', 'string[]'].includes(kind))
      throw new Error(`Unsupported bridge parameter: ${kind}`);
    return { name: p.name.getText(source), kind, nullable };
  }),
}));
const objcType = (p) =>
  p.kind === 'string'
    ? 'NSString *'
    : p.kind === 'string[]'
      ? 'NSArray *'
      : p.nullable
        ? 'NSNumber *'
        : p.kind === 'boolean'
          ? 'BOOL'
          : 'double';
const objcValue = (p) =>
  ['number', 'boolean'].includes(p.kind) && !p.nullable
    ? `@(${p.name})`
    : `${p.name} ?: [NSNull null]`;
const iosMethods = methods
  .map(({ name, params }) => {
    const signature = params.length
      ? params
          .map((p, i) => `${i ? p.name : name}:(${objcType(p)})${p.name}`)
          .join(' ') + ' resolve:(RCTPromiseResolveBlock)resolve'
      : `${name}:(RCTPromiseResolveBlock)resolve`;
    return `- (void)${signature} reject:(RCTPromiseRejectBlock)reject {
  [self invoke:@"${name}" params:@{${params.map((p) => `@"${p.name}": ${objcValue(p)}`).join(', ')}} resolve:resolve reject:reject];
}`;
  })
  .join('\n\n');
